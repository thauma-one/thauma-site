/* ============================================================
   staff-rowpanel.js — one row-with-a-panel, used by all three
   ministry editors
   ============================================================
   Milestones, giving goals and prayer are the same shape of screen: a list of
   rows, and a form that opens directly beneath whichever row you pressed.
   They used to be three separate implementations of that idea, and the copies
   drifted — goals and prayer parked their form at the bottom of the page
   instead of under the row, and a guard renamed in two of the three files
   silently switched the third one off. This is the single copy.

   WHAT IT OWNS: where the form lives in the DOM, the open/close animation,
   which row is marked open, and the scroll that keeps that row in view.
   WHAT IT DOES NOT: anything about the data. Each editor still fills its own
   fields and decides what saving means, because those genuinely differ —
   milestones carry translations and a parent, a goal is one row.
   ============================================================ */
(function () {
  'use strict';

  /* 600ms. The first pass was 420 and cleared "not instant" without clearing
     the real bar: a panel carrying a whole form needs long enough that the eye
     follows the edge down rather than just noticing the result. Matches the
     duration in staff.css. */
  var PANEL_MS = 600;

  function reducedMotion() {
    return window.matchMedia &&
           window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  }

  /* Ids are generated by us, but a row id still ends up inside an attribute
     selector, and CSS.escape is not in older Safari. */
  function cssEscape(s) {
    return window.CSS && CSS.escape ? CSS.escape(s) : String(s).replace(/["\\]/g, '\\$&');
  }

  function stickyTop() {
    var header = document.querySelector('.top');
    return header ? header.offsetHeight : 0;
  }

  /* Height cannot be transitioned to or from `auto`, so each direction
     measures the real height and animates between that and zero, then hands
     control back to the layout. Doing it in JS rather than with a max-height
     guess means the timing is the same for a one-line entry and a long one —
     a max-height large enough for the longest makes short panels appear to
     snap open early and then hang. */
  function openPanel(el) {
    return new Promise(function (resolve) {
      if (!el.hidden) return resolve();
      el.hidden = false;

      if (reducedMotion()) { el.style.height = ''; return resolve(); }

      el.classList.add('is-animating');
      el.style.height = '0px';
      el.style.opacity = '0';
      // Force the browser to accept 0 as a starting point before changing it,
      // or both assignments collapse into one frame and nothing animates.
      void el.offsetHeight;
      el.style.height = el.scrollHeight + 'px';
      el.style.opacity = '1';

      setTimeout(function () {
        // Back to auto so the panel can grow as its content does — a fixed
        // height would clip a description someone keeps typing into.
        el.style.height = '';
        el.style.opacity = '';
        el.classList.remove('is-animating');
        resolve();
      }, PANEL_MS);
    });
  }

  function closePanel(el) {
    return new Promise(function (resolve) {
      if (el.hidden) return resolve();
      if (reducedMotion()) { el.hidden = true; el.style.height = ''; return resolve(); }

      el.classList.add('is-animating');
      el.style.height = el.scrollHeight + 'px';
      el.style.opacity = '1';
      void el.offsetHeight;
      el.style.height = '0px';
      // Fades faster than it collapses (see the CSS), so the text stops being
      // legible early rather than shrinking while still readable — that is
      // what makes a collapsing panel feel like a flicker.
      el.style.opacity = '0';

      setTimeout(function () {
        el.hidden = true;
        el.style.height = '';
        el.style.opacity = '';
        el.classList.remove('is-animating');
        resolve();
      }, PANEL_MS);
    });
  }

  /* opts: { listId, formId, holderId, saveBarId } — saveBarId optional, only
     milestones has a bottom save bar to leave room for. */
  window.StaffRowPanel = function (opts) {
    var $ = function (id) { return document.getElementById(id); };

    function list() { return $(opts.listId); }
    function form() { return $(opts.formId); }
    function holder() { return $(opts.holderId); }

    var api = {
      PANEL_MS: PANEL_MS,
      reducedMotion: reducedMotion,
      cssEscape: cssEscape,

      /* Park the form out of the list before the list is rebuilt, or
         innerHTML takes the form down with the rows. */
      detach: function () {
        var f = form(), h = holder();
        if (f && h && f.parentNode !== h) h.appendChild(f);
        return f;
      },

      rowFor: function (id) {
        var l = list();
        if (!l || !id) return null;
        return l.querySelector('[data-id="' + cssEscape(id) + '"]');
      },

      /* Directly beneath its own row. The form used to sit at the bottom of
         the page, so editing the third of twelve entries meant scrolling past
         nine unrelated rows and losing sight of the one you meant. */
      moveTo: function (id) {
        var f = form(), l = list();
        if (!f || !l) return;
        var row = api.rowFor(id);
        if (row) row.after(f); else l.after(f);
      },

      /* Survives a re-render: the chevron, highlight and sticky position are
         restored from the id being edited rather than reset every refresh. */
      reattach: function (editing) {
        var f = form();
        if (!f || f.hidden || !editing) return;
        var row = api.rowFor(editing);
        if (row) row.after(f);
        api.markOpen(editing);
      },

      /* KEYED ON THE EDITED ID, NOT on the form's hidden attribute. Asking
         whether the panel is visible runs BEFORE openPanel() unhides it, so
         the answer was always "no" and the class was never applied — a sticky
         row that looked like a CSS problem and was a sequencing one. */
      markOpen: function (editing) {
        var l = list();
        if (!l) return;
        Array.prototype.forEach.call(l.querySelectorAll('.ms-row'), function (r) {
          var isOpen = !!(editing && r.dataset.id === editing);
          r.classList.toggle('is-open', isOpen);
          r.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        });
      },

      open: function () { return openPanel(form()); },
      close: function () { return closePanel(form()); },
      isOpen: function () { var f = form(); return !!f && !f.hidden; },

      /* The bar is fixed to the bottom, so the page needs matching padding or
         the last row sits permanently underneath it. Measured rather than
         guessed: the buttons wrap onto a second line on narrow screens. */
      updateStickyOffsets: function () {
        if (!opts.saveBarId) return;
        var bar = $(opts.saveBarId);
        var showing = bar && !bar.hidden;
        document.body.classList.toggle('has-savebar', !!showing);
        if (showing) {
          document.documentElement.style.setProperty(
            '--ms-savebar-h', bar.offsetHeight + 'px');
        }
      },

      /* Put a row's top edge just under the sticky stack.
         scrollIntoView cannot do this: it knows nothing about sticky elements,
         so block:"start" parks the row underneath the header where it cannot
         be seen, and block:"nearest" often does not move at all. */
      scrollRowToTop: function (row) {
        if (!row) return;
        var y = window.scrollY + row.getBoundingClientRect().top - stickyTop() - 10;
        window.scrollTo({
          top: Math.max(0, y),
          behavior: reducedMotion() ? 'auto' : 'smooth'
        });
      },
    };

    return api;
  };
})();
